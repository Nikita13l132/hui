/* Лабораторная работа 6 — Взаимодействие процессов через разделяемую память.
   Программа A (записывающая): вызывает getpwnam_r() (функция №17),
   копирует результат (поле pw_dir) в разделяемую память SVID,
   синхронизация через пару семафоров SVID (sw и sr).

   Логика синхронизации (два семафора, оба начальное значение 0):
     процесс A (запись):          процесс B (чтение):
     while (1) {                  while (1) {
       запись в шм;                 P(sw);   // ждать, когда запишут
       V(sw);  // записал          чтение из шм;
       P(sr);  // ждать чтения    V(sr);   // прочитал
       sleep(1);                  }
     }

   Обработчик SIGINT переустанавливает флаг завершения потока, чтобы
   поток мог выйти из semop() при завершении второй программы. */

#define _GNU_SOURCE
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <signal.h>       /* signal(), SIGINT */
#include <pthread.h>      /* pthread_create(), pthread_join() */
#include <pwd.h>          /* getpwnam_r(), struct passwd */
#include <sys/types.h>
#include <sys/ipc.h>      /* ftok(), IPC_CREAT, IPC_RMID */
#include <sys/shm.h>      /* shmget(), shmat(), shmdt(), shmctl() */
#include <sys/sem.h>      /* semget(), semop(), semctl() */

/* ------------------------------------------------------------------ */
/* Константы                                                            */
/* ------------------------------------------------------------------ */

/* Размер строки домашнего каталога в разделяемой памяти */
#define SHM_SIZE  256

/* Пути для генерации ключей IPC через ftok().
   Оба процесса должны использовать одинаковые пути и proj_id. */
#define KEY_PATH  "/tmp"
#define KEY_ID_SHM  1    /* proj_id для разделяемой памяти */
#define KEY_ID_SEM  2    /* proj_id для набора семафоров */

/* Индексы семафоров в наборе SVID */
#define SW  0   /* семафор записи (write semaphore) */
#define SR  1   /* семафор чтения (read semaphore) */

/* ------------------------------------------------------------------ */
/* Глобальные переменные (доступны из потока и обработчика сигнала)    */
/* ------------------------------------------------------------------ */
static volatile int thread_flag = 0;  /* флаг завершения потока */
static int semid = -1;                /* идентификатор набора семафоров */

/* Операции над семафорами SVID.
   struct sembuf: sem_num — индекс семафора в наборе,
                  sem_op  — операция (>0: V, <0: P),
                  sem_flg — флаги (0 — блокирующий режим) */

/* V(sw) — освободить семафор записи (сообщить "записал") */
static struct sembuf postw[1] = { {SW, +1, 0} };

/* P(sr) — ждать семафора чтения (ждать "прочитал") */
static struct sembuf waitr[1] = { {SR, -1, 0} };

/* ------------------------------------------------------------------ */
/* Обработчик SIGINT                                                    */
/* ------------------------------------------------------------------ */

/* sig_handler — вызывается при нажатии Ctrl+C;
   устанавливает флаг завершения потока, чтобы поток
   вышел из блокирующего semop() при следующей проверке;
   semop() прерывается сигналом и возвращает -1 (errno=EINTR) */
static void sig_handler(int signo)
{
    printf("\nпрограмма A: получен сигнал %d, завершаем работу\n", signo);
    thread_flag = 1;
}

/* ------------------------------------------------------------------ */
/* Идентификатор и локальный адрес разделяемой памяти                  */
/* ------------------------------------------------------------------ */
static int   shmid   = -1;
static char *shm_ptr = NULL;

/* ------------------------------------------------------------------ */
/* Поточная функция: запись в разделяемую память                        */
/* ------------------------------------------------------------------ */
static void *thread_writer(void *arg)
{
    (void)arg;
    printf("поток писатель начал работу\n");

    char pw_buf[1024];  /* вспомогательный буфер для getpwnam_r() */

    while (thread_flag == 0) {

        struct passwd pwd;
        struct passwd *result = NULL;

        /* getpwuid(getuid()) — получение имени текущего пользователя
           по числовому uid; надёжнее getlogin() в нетерминальных сессиях */
        struct passwd *pw_tmp = getpwuid(getuid());
        if (pw_tmp == NULL) {
            perror("getpwuid");
            sleep(1);
            continue;
        }
        char *username = pw_tmp->pw_name;

        /* getpwnam_r — потокобезопасное получение записи из /etc/passwd
           по имени пользователя (функция №17 из таблицы МУ);
           username — имя пользователя для поиска;
           &pwd     — структура для результата;
           pw_buf   — вспомогательный буфер для строковых полей;
           sizeof   — размер вспомогательного буфера;
           &result  — при успехе *result == &pwd, иначе NULL;
           возвращает 0 при успехе, код ошибки при неудаче */
        int rv = getpwnam_r(username, &pwd, pw_buf, sizeof(pw_buf), &result);
        if (rv != 0 || result == NULL) {
            fprintf(stderr, "getpwnam_r: ошибка\n");
            sleep(1);
            continue;
        }

        /* memcpy — копирование pw_dir в разделяемую память;
           dest     — указатель на начало разделяемой памяти;
           src      — строка домашнего каталога (поле pw_dir);
           SHM_SIZE — размер копируемого блока (не более размера шм) */
        memcpy(shm_ptr, pwd.pw_dir, SHM_SIZE);
        /* гарантируем нуль-терминатор на случай длинной строки */
        shm_ptr[SHM_SIZE - 1] = '\0';

        printf("[писатель] записано в шм: '%s'\n", shm_ptr);

        /* semop — V(sw): увеличить семафор записи на 1;
           сообщаем процессу B, что данные записаны и можно читать;
           &postw[0].sem_num=SW, sem_op=+1, sem_flg=0 (блокирующий) */
        if (semop(semid, postw, 1) == -1) {
            if (thread_flag == 0) perror("semop postw");
            break;
        }

        /* semop — P(sr): уменьшить семафор чтения на 1;
           блокируемся до тех пор, пока процесс B не прочитает данные
           и не вызовет V(sr); гарантирует, что мы не перезапишем
           разделяемую память до завершения чтения;
           &waitr[0].sem_num=SR, sem_op=-1, sem_flg=0 (блокирующий) */
        if (semop(semid, waitr, 1) == -1) {
            if (thread_flag == 0) perror("semop waitr");
            break;
        }

        sleep(1); /* задержка 1 с перед следующей записью */
    }

    printf("поток писатель закончил работу\n");
    pthread_exit((void *)1);
    return NULL;
}

/* ------------------------------------------------------------------ */
/* Вспомогательный union для semctl() — требуется стандартом SVID      */
/* ------------------------------------------------------------------ */
union semun {
    int              val;
    struct semid_ds *buf;
    unsigned short  *array;
};

/* ------------------------------------------------------------------ */
/* Основная программа                                                   */
/* ------------------------------------------------------------------ */
int main(void)
{
    printf("программа A начала работу\n");

    /* --- Регистрация обработчика SIGINT ----------------------------- */

    /* signal — замена системного обработчика SIGINT на sig_handler;
       при Ctrl+C поток выйдет из semop() через EINTR */
    signal(SIGINT, sig_handler);

    /* --- Создание разделяемой памяти SVID --------------------------- */

    /* ftok — генерация ключа IPC из пути и числа proj_id;
       оба процесса с одинаковыми аргументами получат одинаковый ключ;
       KEY_PATH="/tmp", KEY_ID_SHM=1 */
    key_t key_shm = ftok(KEY_PATH, KEY_ID_SHM);
    if (key_shm == -1) {
        perror("ftok shm");
        return 1;
    }

    /* shmget — создание (или открытие существующего) сегмента
       разделяемой памяти SVID;
       key_shm    — ключ IPC (одинаковый в обоих процессах);
       SHM_SIZE   — требуемый размер сегмента в байтах;
       IPC_CREAT  — создать если не существует;
       0644       — права: владелец читает/пишет, остальные читают;
       возвращает идентификатор сегмента или -1 при ошибке */
    shmid = shmget(key_shm, SHM_SIZE, IPC_CREAT | 0644);
    if (shmid == -1) {
        perror("shmget");
        return 1;
    }
    printf("программа A: разделяемая память создана, shmid=%d\n", shmid);

    /* shmat — подключение сегмента разделяемой памяти к адресному
       пространству процесса;
       shmid  — идентификатор сегмента;
       NULL   — ядро само выбирает адрес подключения;
       0      — флаги по умолчанию (чтение и запись);
       возвращает указатель на начало сегмента или (void*)-1 при ошибке */
    shm_ptr = (char *)shmat(shmid, NULL, 0);
    if (shm_ptr == (char *)-1) {
        perror("shmat");
        return 1;
    }
    printf("программа A: разделяемая память подключена по адресу %p\n",
           (void *)shm_ptr);

    /* --- Создание набора семафоров SVID ----------------------------- */

    /* ftok — генерация ключа IPC для набора семафоров */
    key_t key_sem = ftok(KEY_PATH, KEY_ID_SEM);
    if (key_sem == -1) {
        perror("ftok sem");
        return 1;
    }

    /* semget — создание (или открытие) набора из 2 семафоров SVID;
       key_sem   — ключ IPC;
       2         — число семафоров в наборе (SW и SR);
       IPC_CREAT — создать если не существует;
       0644      — права доступа */
    semid = semget(key_sem, 2, IPC_CREAT | 0644);
    if (semid == -1) {
        perror("semget");
        return 1;
    }
    printf("программа A: набор семафоров создан, semid=%d\n", semid);

    /* semctl — инициализация семафоров;
       SETVAL  — установить значение одного семафора;
       SW = 0  — семафор записи: 0 (данных ещё нет, читать нельзя);
       SR = 0  — семафор чтения: 0 (чтение ещё не было, писать сразу можно
                 т.к. процесс A пишет ПЕРЕД V(sw), P(sr) не блокирует
                 первую итерацию — он идёт ПОСЛЕ V(sw)) */
    union semun su;
    su.val = 0;

    /* semctl — установка начального значения семафора записи (SW=0) */
    if (semctl(semid, SW, SETVAL, su) == -1) {
        perror("semctl SETVAL SW");
        return 1;
    }

    /* semctl — установка начального значения семафора чтения (SR=0) */
    if (semctl(semid, SR, SETVAL, su) == -1) {
        perror("semctl SETVAL SR");
        return 1;
    }
    printf("программа A: семафоры инициализированы (SW=0, SR=0)\n");

    /* --- Создание потока ------------------------------------------- */

    pthread_t tid;

    /* pthread_create — создание потока-писателя */
    if (pthread_create(&tid, NULL, thread_writer, NULL) != 0) {
        perror("pthread_create");
        return 1;
    }

    printf("программа A: для завершения нажмите <Enter>\n");

    /* getchar — блокирующее ожидание нажатия <Enter> */
    getchar();

    /* Устанавливаем флаг завершения — поток выйдет из цикла */
    thread_flag = 1;

    /* pthread_join — ожидание завершения потока-писателя */
    void *ec = NULL;
    pthread_join(tid, &ec);
    printf("поток завершился с кодом: %ld\n", (long)ec);

    /* --- Завершение: отключение и удаление ресурсов IPC ------------ */

    /* shmdt — отключение разделяемой памяти от адресного пространства;
       shm_ptr — локальный адрес, полученный через shmat() */
    if (shmdt(shm_ptr) == -1) {
        perror("shmdt");
    }

    /* shmctl(IPC_RMID) — удаление сегмента разделяемой памяти;
       IPC_RMID — команда: пометить сегмент для удаления;
       NULL     — третий параметр не используется при IPC_RMID */
    if (shmctl(shmid, IPC_RMID, NULL) == -1) {
        perror("shmctl IPC_RMID");
    }

    /* semctl(IPC_RMID) — удаление набора семафоров */
    if (semctl(semid, 0, IPC_RMID) == -1) {
        perror("semctl IPC_RMID");
    }

    printf("программа A завершила работу\n");
    return 0;
}
