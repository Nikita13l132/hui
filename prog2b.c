/* Лабораторная работа 6 — Взаимодействие процессов через разделяемую память.
   Программа B (читающая): читает данные из разделяемой памяти SVID
   (строку pw_dir, записанную программой A через getpwnam_r()),
   синхронизация через пару семафоров SVID (sw и sr).

   Логика синхронизации (два семафора, оба начальное значение 0):
     процесс A (запись):          процесс B (чтение):
     while (1) {                  while (1) {
       запись в шм;                 P(sw);   // ждать, когда запишут
       V(sw);  // записал          чтение из шм;
       P(sr);  // ждать чтения    V(sr);   // прочитал
       sleep(1);                  }
     }

   Обработчик SIGINT устанавливает флаг завершения потока, чтобы поток
   мог выйти из блокирующего semop() при завершении программы A. */

#define _GNU_SOURCE
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include <signal.h>       /* signal(), SIGINT */
#include <pthread.h>
#include <sys/types.h>
#include <sys/ipc.h>      /* ftok(), IPC_CREAT */
#include <sys/shm.h>      /* shmget(), shmat(), shmdt(), shmctl() */
#include <sys/sem.h>      /* semget(), semop(), semctl() */

/* ------------------------------------------------------------------ */
/* Константы — должны совпадать с программой A                         */
/* ------------------------------------------------------------------ */
#define SHM_SIZE    256
#define KEY_PATH    "/tmp"
#define KEY_ID_SHM  1
#define KEY_ID_SEM  2
#define SW  0
#define SR  1

/* ------------------------------------------------------------------ */
/* Глобальные переменные                                                */
/* ------------------------------------------------------------------ */
static volatile int thread_flag = 0;
static int semid  = -1;
static int shmid  = -1;
static char *shm_ptr = NULL;

/* Операции над семафорами SVID.
   P(sw) — ждать семафора записи (ждать "записал") */
static struct sembuf waitw[1] = { {SW, -1, 0} };

/* V(sr) — освободить семафор чтения (сообщить "прочитал") */
static struct sembuf postr[1] = { {SR, +1, 0} };

/* ------------------------------------------------------------------ */
/* Обработчик SIGINT                                                    */
/* ------------------------------------------------------------------ */

/* sig_handler — при Ctrl+C устанавливает флаг завершения;
   semop() прерывается сигналом (errno=EINTR), поток выходит из цикла */
static void sig_handler(int signo)
{
    printf("\nпрограмма B: получен сигнал %d, завершаем работу\n", signo);
    thread_flag = 1;
}

/* ------------------------------------------------------------------ */
/* Поточная функция: чтение из разделяемой памяти                       */
/* ------------------------------------------------------------------ */
static void *thread_reader(void *arg)
{
    (void)arg;
    printf("поток читатель начал работу\n");

    char local_buf[SHM_SIZE]; /* локальная переменная для прочитанных данных */

    while (thread_flag == 0) {

        /* semop — P(sw): уменьшить семафор записи на 1;
           блокируемся до тех пор, пока программа A не запишет данные
           и не вызовет V(sw); гарантирует, что мы не читаем из
           пустой или непереписанной разделяемой памяти;
           sem_num=SW, sem_op=-1, sem_flg=0 (блокирующий режим) */
        if (semop(semid, waitw, 1) == -1) {
            if (thread_flag == 0) perror("semop waitw");
            break;
        }

        /* memcpy — копирование данных из разделяемой памяти
           в локальную переменную;
           dest      — локальный буфер;
           shm_ptr   — начало разделяемой памяти (записано программой A);
           SHM_SIZE  — размер копируемого блока */
        memcpy(local_buf, shm_ptr, SHM_SIZE);
        local_buf[SHM_SIZE - 1] = '\0'; /* гарантируем нуль-терминатор */

        printf("[читатель] прочитано из шм: '%s'\n", local_buf);

        /* semop — V(sr): увеличить семафор чтения на 1;
           сообщаем программе A, что данные прочитаны и можно
           выполнять следующую запись;
           sem_num=SR, sem_op=+1, sem_flg=0 */
        if (semop(semid, postr, 1) == -1) {
            if (thread_flag == 0) perror("semop postr");
            break;
        }
    }

    printf("поток читатель закончил работу\n");
    pthread_exit((void *)2);
    return NULL;
}

/* ------------------------------------------------------------------ */
/* Вспомогательный union для semctl()                                   */
/* ------------------------------------------------------------------ */
union semun {
    int              val;
    struct semid_ds *buf;
    unsigned short  *array;
};

/* ------------------------------------------------------------------ */
/* Основная программа                                                   */
/* ------------------------------------------------------------------ */
int main(void)
{
    printf("программа B начала работу\n");

    /* signal — замена системного обработчика SIGINT на sig_handler */
    signal(SIGINT, sig_handler);

    /* --- Открытие разделяемой памяти SVID -------------------------- */

    /* ftok — генерация ключа IPC для разделяемой памяти;
       те же аргументы, что и в программе A — получим тот же ключ */
    key_t key_shm = ftok(KEY_PATH, KEY_ID_SHM);
    if (key_shm == -1) {
        perror("ftok shm");
        return 1;
    }

    /* shmget — открытие существующего сегмента разделяемой памяти;
       key_shm  — тот же ключ, что у программы A (получим тот же сегмент);
       SHM_SIZE — размер должен совпадать с программой A;
       IPC_CREAT — создать если ещё не создан (на случай запуска B первой);
       0644     — права доступа */
    shmid = shmget(key_shm, SHM_SIZE, IPC_CREAT | 0644);
    if (shmid == -1) {
        perror("shmget");
        return 1;
    }
    printf("программа B: разделяемая память открыта, shmid=%d\n", shmid);

    /* shmat — подключение сегмента к адресному пространству процесса;
       NULL — ядро выбирает адрес; 0 — флаги по умолчанию */
    shm_ptr = (char *)shmat(shmid, NULL, 0);
    if (shm_ptr == (char *)-1) {
        perror("shmat");
        return 1;
    }
    printf("программа B: разделяемая память подключена по адресу %p\n",
           (void *)shm_ptr);

    /* --- Открытие набора семафоров SVID ----------------------------- */

    /* ftok — генерация ключа IPC для семафоров */
    key_t key_sem = ftok(KEY_PATH, KEY_ID_SEM);
    if (key_sem == -1) {
        perror("ftok sem");
        return 1;
    }

    /* semget — открытие существующего набора семафоров;
       те же ключ и число семафоров, что в программе A */
    semid = semget(key_sem, 2, IPC_CREAT | 0644);
    if (semid == -1) {
        perror("semget");
        return 1;
    }
    printf("программа B: набор семафоров открыт, semid=%d\n", semid);

    /* --- Создание потока ------------------------------------------- */

    pthread_t tid;

    /* pthread_create — создание потока-читателя */
    if (pthread_create(&tid, NULL, thread_reader, NULL) != 0) {
        perror("pthread_create");
        return 1;
    }

    printf("программа B: для завершения нажмите <Enter>\n");

    /* getchar — блокирующее ожидание нажатия <Enter> */
    getchar();

    thread_flag = 1;

    /* pthread_join — ожидание завершения потока-читателя */
    void *ec = NULL;
    pthread_join(tid, &ec);
    printf("поток завершился с кодом: %ld\n", (long)ec);

    /* --- Завершение: отключение ресурсов IPC ----------------------- */

    /* shmdt — отключение разделяемой памяти от адресного пространства */
    if (shmdt(shm_ptr) == -1) {
        perror("shmdt");
    }

    /* Программа B НЕ удаляет сегмент и семафоры через IPC_RMID —
       это делает программа A, которая их создавала */

    printf("программа B завершила работу\n");
    return 0;
}
